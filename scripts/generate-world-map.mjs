// Generates lib/content/worldMap.ts from Natural Earth data (public domain,
// via the world-atlas package).
//
// Run at build-authoring time, not at runtime: the output is a handful of SVG
// path strings, so the app ships no map library and no TopoJSON.
import fs from "node:fs";
import { feature } from "topojson-client";
import { geoEquirectangular, geoPath } from "d3-geo";

const WIDTH = 1000;
const HEIGHT = 500;

// Numeric ISO 3166-1 codes, which is how Natural Earth identifies countries.
const HIGHLIGHT = {
  US: "840",
  GB: "826",
  IN: "356",
  AU: "036",
  SG: "702",
  HK: "344",
  DE: "276",
  FR: "250",
  CA: "124",
  NZ: "554",
};

const topo = JSON.parse(fs.readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"));
const countries = feature(topo, topo.objects.countries);

// Equirectangular so a lat/lon marker can be projected with plain arithmetic
// in the component, without shipping d3-geo to the browser.
const projection = geoEquirectangular()
  .scale(HEIGHT / Math.PI)
  .translate([WIDTH / 2, HEIGHT / 2]);
const path = geoPath(projection);

const byId = new Map(countries.features.map((f) => [String(f.id), f]));

const highlighted = new Set(Object.values(HIGHLIGHT));
const base = {
  type: "FeatureCollection",
  // Antarctica (010) is dropped: it spans the full width as a band along the
  // bottom, dominates the silhouette, and no supported country is near it.
  features: countries.features.filter((f) => !highlighted.has(String(f.id)) && String(f.id) !== "010"),
};

// Integer coordinates: at a 1000px-wide viewBox a tenth of a pixel is
// invisible, and the decimals were most of the payload.
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n))));

const shapes = {};
const missing = [];
for (const [iso, id] of Object.entries(HIGHLIGHT)) {
  const f = byId.get(id);
  if (!f) {
    missing.push(iso);
    continue;
  }
  shapes[iso] = round(path(f));
}

const out = `// GENERATED by scripts/generate-world-map.mjs -- do not edit by hand.
//
// Natural Earth 110m country outlines (public domain), projected
// equirectangular into a ${WIDTH}x${HEIGHT} viewBox. Only the countries we
// support are kept as separate shapes so they can be filled when selected;
// everything else is one merged path.
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

export const WORLD_PATH = ${JSON.stringify(round(path(base)))};

export const COUNTRY_PATHS: Record<string, string> = ${JSON.stringify(shapes, null, 2)};
`;

fs.mkdirSync("lib/content", { recursive: true });
fs.writeFileSync("lib/content/worldMap.ts", out);

console.log(`wrote lib/content/worldMap.ts`);
console.log(`  base path: ${round(path(base)).length} chars`);
for (const [iso, d] of Object.entries(shapes)) console.log(`  ${iso}: ${d.length} chars`);
if (missing.length) console.log(`  NOT IN DATASET: ${missing.join(", ")}`);
